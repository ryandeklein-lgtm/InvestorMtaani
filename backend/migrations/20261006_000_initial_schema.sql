-- Baseline schema for a new Investor Mtaani PostgreSQL database.
-- Every object is created only when absent so existing installations retain data.

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('business', 'investor', 'admin')),
  phone TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  terms_accepted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS businesses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  business_name TEXT NOT NULL,
  industry TEXT NOT NULL,
  location TEXT NOT NULL,
  description TEXT NOT NULL,
  year_established INTEGER,
  employees INTEGER,
  annual_revenue NUMERIC(16, 2),
  monthly_gross NUMERIC(16, 2),
  monthly_net NUMERIC(16, 2),
  amount_seeking NUMERIC(16, 2),
  funding_reason TEXT,
  investment_structure TEXT,
  use_of_funds TEXT,
  business_stage TEXT,
  registration_number TEXT,
  kra_pin TEXT,
  risk_disclosure TEXT,
  status TEXT NOT NULL DEFAULT 'draft',
  review_notes TEXT,
  verified_at TIMESTAMPTZ,
  views BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS businesses_public_listing_idx
  ON businesses (status, created_at DESC);
CREATE INDEX IF NOT EXISTS businesses_owner_idx
  ON businesses (user_id);

CREATE TABLE IF NOT EXISTS investors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  display_name TEXT NOT NULL,
  investor_type TEXT,
  location TEXT,
  thesis TEXT,
  min_check_size NUMERIC(16, 2),
  max_check_size NUMERIC(16, 2),
  preferred_stage TEXT,
  sectors_of_interest TEXT,
  geographic_focus TEXT,
  preferred_structure TEXT,
  investing_status TEXT,
  portfolio_highlights TEXT,
  verification_status TEXT NOT NULL DEFAULT 'pending',
  views BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS investors_owner_idx ON investors (user_id);

CREATE TABLE IF NOT EXISTS matchmaking_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  investor_id BIGINT NOT NULL REFERENCES users(id),
  business_id BIGINT NOT NULL REFERENCES businesses(id),
  investment_amount NUMERIC(16, 2),
  investment_type TEXT,
  message TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  special_request BOOLEAN NOT NULL DEFAULT FALSE,
  fee_amount NUMERIC(16, 2),
  fee_status TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS matchmaking_investor_created_idx
  ON matchmaking_requests (investor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS matchmaking_business_created_idx
  ON matchmaking_requests (business_id, created_at DESC);

CREATE TABLE IF NOT EXISTS funding_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id BIGINT NOT NULL REFERENCES businesses(id),
  amount_requested NUMERIC(16, 2) NOT NULL,
  amount_raised NUMERIC(16, 2) NOT NULL DEFAULT 0,
  funding_type TEXT,
  funding_reason TEXT,
  expected_impact TEXT,
  funding_timeline TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS funding_requests_status_created_idx
  ON funding_requests (status, created_at DESC);

CREATE TABLE IF NOT EXISTS startups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id),
  startup_name TEXT NOT NULL,
  industry TEXT,
  location TEXT,
  description TEXT,
  year_established INTEGER,
  employees INTEGER,
  annual_revenue NUMERIC(16, 2),
  monthly_gross NUMERIC(16, 2),
  monthly_net NUMERIC(16, 2),
  website_visitors BIGINT,
  investment_readiness_score NUMERIC(6, 2),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
