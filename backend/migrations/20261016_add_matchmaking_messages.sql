CREATE TABLE IF NOT EXISTS matchmaking_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES matchmaking_requests(id) ON DELETE CASCADE,
  sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 2000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS matchmaking_messages_request_created_idx
  ON matchmaking_messages (request_id, created_at ASC, id ASC);

CREATE INDEX IF NOT EXISTS matchmaking_messages_unread_idx
  ON matchmaking_messages (request_id, created_at DESC)
  WHERE read_at IS NULL;
