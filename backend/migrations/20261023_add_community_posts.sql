CREATE TABLE IF NOT EXISTS community_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL DEFAULT '' CHECK (char_length(body) <= 1000),
  media BYTEA,
  media_mime TEXT,
  media_size INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (media IS NULL AND media_mime IS NULL AND media_size IS NULL)
    OR
    (media IS NOT NULL AND media_mime IS NOT NULL AND media_size IS NOT NULL
      AND media_mime IN ('image/jpeg', 'image/png', 'image/webp', 'video/mp4', 'video/webm')
      AND media_size BETWEEN 1 AND 26214400 AND octet_length(media) = media_size)
  ),
  CHECK (char_length(btrim(body)) > 0 OR media IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS community_posts_business_created_idx
  ON community_posts (business_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS community_post_likes (
  post_id BIGINT NOT NULL REFERENCES community_posts(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (post_id, user_id)
);

CREATE INDEX IF NOT EXISTS community_post_likes_user_idx
  ON community_post_likes (user_id, post_id);
